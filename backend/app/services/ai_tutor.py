"""AI Tutor service — explains the rule-based recommendation in plain language.

If OPENAI_API_KEY is set in the environment the explanation is generated by
gpt-4o-mini.  Otherwise a deterministic local explanation is built directly
from the analysis data so the application works without any API key.
"""
from __future__ import annotations

import os
import textwrap
from typing import Any


# ── helpers ──────────────────────────────────────────────────────────────────

def _col(refs: list[dict]) -> str:
    return ", ".join(f"{r['table']}.{r['column']}" for r in refs) or "none"


def _plan_summary(plan: list[dict]) -> str:
    return "; ".join(s.get("detail", "") for s in plan) if plan else "not available"


# ── local (deterministic) explanation ────────────────────────────────────────

def _local_explanation(payload: dict) -> dict:
    """Build a structured explanation purely from the analysis data."""
    rec   = payload.get("rec", {})
    plan  = payload.get("plan", {})
    query = rec.get("query", "")
    analysis = rec.get("analysis", {})
    recs  = rec.get("recommendations", [])
    rejected = rec.get("rejected_candidates", [])
    plan_steps = plan.get("plan", [])

    tables   = analysis.get("tables", [])
    eq_cols  = analysis.get("equality_filters", [])
    rng_cols = analysis.get("range_filters", [])
    join_cols= analysis.get("join_columns", [])
    ord_cols = analysis.get("order_by_columns", [])
    grp_cols = analysis.get("group_by_columns", [])

    rec0 = recs[0] if recs else None

    # ── what the query does ──
    parts = []
    if tables:
        parts.append(f"The query reads from {', '.join(tables)}.")
    if eq_cols:
        parts.append(
            f"It filters rows using equality conditions on "
            f"{_col(eq_cols)}, which means SQLite must find rows where "
            f"those columns match exact values."
        )
    if rng_cols:
        parts.append(
            f"It also applies range conditions on {_col(rng_cols)}, "
            f"requiring SQLite to scan a range of values."
        )
    if join_cols:
        parts.append(
            f"The query joins tables on {_col(join_cols)}, so SQLite "
            f"must match rows between tables using those columns."
        )
    if ord_cols:
        parts.append(
            f"Results are sorted by {_col(ord_cols)}, which requires "
            f"SQLite to order the output rows."
        )
    if grp_cols:
        parts.append(
            f"Rows are grouped by {_col(grp_cols)}."
        )
    query_summary = " ".join(parts) if parts else "The query selects rows from the database."

    # ── features detected ──
    feature_lines = []
    if eq_cols:
        for c in eq_cols:
            feature_lines.append(
                f"• {c['table']}.{c['column']} — equality filter (+45 pts): "
                f"filtering on an exact value is highly selective and benefits most from an index."
            )
    if rng_cols:
        for c in rng_cols:
            feature_lines.append(
                f"• {c['table']}.{c['column']} — range filter (+25 pts): "
                f"an index lets SQLite jump to the start of the range instead of scanning every row."
            )
    if join_cols:
        for c in join_cols:
            feature_lines.append(
                f"• {c['table']}.{c['column']} — join column (+35 pts): "
                f"an index speeds up row matching between tables."
            )
    if ord_cols:
        for c in ord_cols:
            feature_lines.append(
                f"• {c['table']}.{c['column']} — ORDER BY (+15 pts): "
                f"if the index is already sorted on this column, SQLite can skip the sort step."
            )
    if grp_cols:
        for c in grp_cols:
            feature_lines.append(
                f"• {c['table']}.{c['column']} — GROUP BY (+15 pts): "
                f"an index on the grouping column reduces the work needed to aggregate rows."
            )
    features_text = "\n".join(feature_lines) if feature_lines else "No indexable features were detected."

    # ── why this index ──
    if rec0:
        cols_str = ", ".join(rec0["columns"])
        why_parts = [
            f"The engine recommended an index on {rec0['table']}({cols_str}) "
            f"with a score of {rec0['score']} ({rec0['confidence']} confidence)."
        ]
        if rec0.get("reasons"):
            why_parts.append("Reasons given by the engine:")
            why_parts += [f"  • {r}" for r in rec0["reasons"]]
        if len(rec0["columns"]) > 1:
            why_parts.append(
                f"The columns are ordered with equality columns first "
                f"({', '.join(rec0['columns'][:-1])}) followed by any range column "
                f"({rec0['columns'][-1]}). SQLite composite indexes work best when "
                f"equality predicates come before range predicates."
            )
        why_index = "\n".join(why_parts)
    elif rejected:
        why_index = (
            "No new index was recommended. "
            + " ".join(r["reason"] for r in rejected)
        )
    else:
        why_index = "No indexable columns were detected in this query."

    # ── simple explanation ──
    if rec0:
        simple = (
            f"Without an index, SQLite reads every row in {rec0['table']} to find "
            f"the ones you want — like flipping through every page of a book. "
            f"Adding an index on ({', '.join(rec0['columns'])}) is like adding a "
            f"bookmark: SQLite can jump straight to the right rows instead of "
            f"reading everything."
        )
    else:
        simple = (
            "SQLite already has what it needs to answer this query efficiently. "
            "No new index is required."
        )

    # ── technical explanation ──
    if rec0:
        tech = (
            f"The rule-based engine scored candidates using evidence weights: "
            f"equality filter +45, join +35, range filter +25, ORDER BY/GROUP BY +15, "
            f"composite predicate +65. "
            f"The top candidate {rec0['table']}({', '.join(rec0['columns'])}) "
            f"received the project-defined score {rec0['score']}. "
            f"Candidates whose column prefix matched an existing index or primary key "
            f"were rejected. "
            f"The CREATE INDEX statement is: {rec0['create_index_sql']}"
        )
    else:
        tech = (
            "All generated candidates were rejected because existing indexes or "
            "primary keys already cover the access patterns in this query. "
            "Adding a duplicate index would increase write overhead without "
            "improving read performance."
        )

    # ── trade-offs ──
    if rec0:
        tradeoffs = textwrap.dedent(f"""
            • Read performance: SELECT queries filtering or sorting on \
({', '.join(rec0['columns'])}) will be faster.
            • Write overhead: every INSERT, UPDATE, or DELETE on \
{rec0['table']} must also update the index, adding a small cost.
            • Storage: the index occupies additional disk space proportional \
to the number of rows in {rec0['table']}.
            • Maintenance: indexes can become fragmented over time and may \
benefit from periodic REINDEX.
            • Over-indexing: too many indexes slow down writes more than they \
help reads — only add indexes that are actually used.
        """).strip()
    else:
        tradeoffs = (
            "No new index was recommended, so no additional trade-offs apply. "
            "Existing indexes already carry their own write overhead."
        )

    # ── query plan meaning ──
    if plan_steps:
        plan_lines = []
        for s in plan_steps:
            detail = s.get("detail", "")
            if "SCAN" in detail.upper() and "USING" not in detail.upper():
                plan_lines.append(
                    f"'{detail}' — SQLite is performing a full table scan, "
                    f"reading every row. This is the pattern an index would eliminate."
                )
            elif "SEARCH" in detail.upper() and "USING INDEX" in detail.upper():
                plan_lines.append(
                    f"'{detail}' — SQLite is using an existing index to look up "
                    f"only the matching rows. This is efficient."
                )
            elif "SEARCH" in detail.upper():
                plan_lines.append(
                    f"'{detail}' — SQLite is searching with some constraint, "
                    f"but may not be using an index."
                )
            else:
                plan_lines.append(f"'{detail}'")
        plan_meaning = "\n".join(f"• {l}" for l in plan_lines)
    else:
        plan_meaning = "No query plan was available for this analysis."

    return {
        "source": "local",
        "query_summary":    query_summary,
        "features_detected": features_text,
        "why_this_index":   why_index,
        "simple_explanation": simple,
        "technical_explanation": tech,
        "tradeoffs":        tradeoffs,
        "query_plan_meaning": plan_meaning,
    }


# ── OpenAI explanation ────────────────────────────────────────────────────────

def _build_system_prompt() -> str:
    return (
        "You are an expert database tutor explaining SQLite index recommendations "
        "to students. The recommendation was produced by a deterministic rule-based "
        "engine — you must NOT change, override, or second-guess it. "
        "Your role is purely educational: explain what the engine found and why. "
        "Be concise, accurate, and friendly. Use plain language for simple "
        "explanations and precise technical language for technical ones. "
        "Never invent performance numbers or benchmarks."
    )


def _build_user_prompt(payload: dict) -> str:
    rec   = payload.get("rec", {})
    plan  = payload.get("plan", {})
    analysis = rec.get("analysis", {})
    recs  = rec.get("recommendations", [])
    rejected = rec.get("rejected_candidates", [])

    lines = [
        f"SQL query:\n{rec.get('query', '')}",
        f"Tables: {', '.join(analysis.get('tables', []))}",
        f"WHERE equality: {_col(analysis.get('equality_filters', []))}",
        f"WHERE range: {_col(analysis.get('range_filters', []))}",
        f"JOIN columns: {_col(analysis.get('join_columns', []))}",
        f"ORDER BY: {_col(analysis.get('order_by_columns', []))}",
        f"GROUP BY: {_col(analysis.get('group_by_columns', []))}",
        f"Query plan: {_plan_summary(plan.get('plan', []))}",
    ]
    if recs:
        r = recs[0]
        lines += [
            f"Recommended index: {r['table']}({', '.join(r['columns'])})",
            f"Score: {r['score']}  Confidence: {r['confidence']}",
            f"CREATE INDEX: {r['create_index_sql']}",
            f"Reasons: {'; '.join(r['reasons'])}",
        ]
    if rejected:
        lines.append(
            "Rejected candidates: "
            + "; ".join(f"{r['table']}({', '.join(r['columns'])}): {r['reason']}" for r in rejected)
        )

    context = "\n".join(lines)

    return (
        f"Here is the analysis result from the rule-based engine:\n\n{context}\n\n"
        "Please provide a JSON object with exactly these keys:\n"
        "  query_summary, features_detected, why_this_index, "
        "simple_explanation, technical_explanation, tradeoffs, query_plan_meaning\n"
        "Each value is a plain string (no markdown headers, no bullet symbols in "
        "simple_explanation). Keep each section under 120 words."
    )


async def _openai_explanation(payload: dict, api_key: str) -> dict:
    """Call OpenAI chat completions. Returns parsed dict or raises."""
    import json as _json
    try:
        import httpx
    except ImportError:
        raise RuntimeError("httpx not available")

    body = {
        "model": "gpt-4o-mini",
        "response_format": {"type": "json_object"},
        "max_tokens": 1200,
        "messages": [
            {"role": "system", "content": _build_system_prompt()},
            {"role": "user",   "content": _build_user_prompt(payload)},
        ],
    }
    async with httpx.AsyncClient(timeout=30) as client:
        resp = await client.post(
            "https://api.openai.com/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}",
                     "Content-Type": "application/json"},
            json=body,
        )
        resp.raise_for_status()
        content = resp.json()["choices"][0]["message"]["content"]
        data = _json.loads(content)
        data["source"] = "openai"
        return data


# ── follow-up answer ──────────────────────────────────────────────────────────

_FOLLOWUP_PATTERNS: list[tuple[list[str], str]] = [
    (
        ["composite", "multiple column", "why not single"],
        "A composite index covers multiple columns in one structure. "
        "When a query filters on several columns together, a composite index "
        "lets SQLite satisfy all conditions with a single index lookup instead "
        "of multiple separate lookups. The rule-based engine creates composites "
        "when it detects multiple equality filters on the same table, placing "
        "equality columns first and any range column last — matching SQLite's "
        "left-prefix rule.",
    ),
    (
        ["explain query plan", "what does", "scan", "search"],
        "EXPLAIN QUERY PLAN shows how SQLite intends to execute your query. "
        "'SCAN tablename' means SQLite will read every row — a full table scan. "
        "'SEARCH tablename USING INDEX' means SQLite will use an index to jump "
        "directly to matching rows, which is much faster for large tables. "
        "The goal of index recommendations is to turn SCANs into SEARCHes.",
    ),
    (
        ["trade-off", "tradeoff", "downside", "cost", "overhead"],
        "Every index speeds up reads but slows down writes slightly, because "
        "SQLite must update the index on every INSERT, UPDATE, or DELETE. "
        "Indexes also consume disk space. The rule-based engine only recommends "
        "indexes only when query features support them, while rejecting candidates "
        "already covered by a primary key or existing index.",
    ),
    (
        ["score", "confidence", "how is score", "how is confidence"],
        "The engine uses fixed feature scores: equality filter 45, join 35, "
        "range filter 25, ORDER BY or GROUP BY 15, and composite predicate exactly 65. "
        "Confidence is 'high' for score ≥ 65, "
        "'medium' for ≥ 35, and 'low' below that.",
    ),
    (
        ["primary key", "why not primary"],
        "Primary keys are automatically indexed by SQLite. The engine rejects "
        "any candidate whose column prefix matches the primary key to avoid "
        "creating a redundant index.",
    ),
    (
        ["existing index", "already covered", "rejected"],
        "If an existing index already covers the candidate columns (its left "
        "prefix matches), adding another index would waste space and write "
        "overhead without improving performance. The engine marks these as "
        "rejected candidates and explains why.",
    ),
    (
        ["order", "column order", "why first", "why last"],
        "In a composite index, SQLite can only use the index efficiently if "
        "the query predicates match the index columns from left to right "
        "(the left-prefix rule). Equality columns come first because they "
        "narrow the search most aggressively; a range column comes last "
        "because it can only be used after all equality columns are matched.",
    ),
]


def _local_followup(question: str, payload: dict) -> str:
    q = question.lower()
    for keywords, answer in _FOLLOWUP_PATTERNS:
        if any(kw in q for kw in keywords):
            return answer

    # generic fallback using analysis context
    rec = payload.get("rec", {})
    recs = rec.get("recommendations", [])
    if recs:
        r = recs[0]
        return (
            f"Based on the current analysis: the engine recommended an index on "
            f"{r['table']}({', '.join(r['columns'])}) with score {r['score']} "
            f"({r['confidence']} confidence). "
            f"If your question is about a specific aspect of this recommendation, "
            f"try asking about: composite indexes, column order, score/confidence, "
            f"trade-offs, or what EXPLAIN QUERY PLAN means."
        )
    return (
        "No recommendation was generated for this query — existing indexes or "
        "primary keys already cover the access patterns. Try asking about "
        "trade-offs, score/confidence, or EXPLAIN QUERY PLAN."
    )


async def _openai_followup(question: str, payload: dict, api_key: str) -> str:
    import json as _json
    try:
        import httpx
    except ImportError:
        raise RuntimeError("httpx not available")

    context = _build_user_prompt(payload)
    messages = [
        {"role": "system", "content": _build_system_prompt()},
        {"role": "user",   "content": context},
        {"role": "assistant", "content": "(explanation already provided)"},
        {"role": "user",   "content": question},
    ]
    body = {
        "model": "gpt-4o-mini",
        "max_tokens": 300,
        "messages": messages,
    }
    async with httpx.AsyncClient(timeout=20) as client:
        resp = await client.post(
            "https://api.openai.com/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}",
                     "Content-Type": "application/json"},
            json=body,
        )
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"].strip()


# ── public API ────────────────────────────────────────────────────────────────

async def explain(payload: dict) -> dict:
    """Return a structured explanation. Uses OpenAI if key is configured."""
    api_key = os.getenv("OPENAI_API_KEY", "").strip()
    if api_key:
        try:
            return await _openai_explanation(payload, api_key)
        except Exception:
            pass  # fall through to local
    return _local_explanation(payload)


async def followup(question: str, payload: dict) -> str:
    """Answer a follow-up question. Uses OpenAI if key is configured."""
    api_key = os.getenv("OPENAI_API_KEY", "").strip()
    if api_key:
        try:
            return await _openai_followup(question, payload, api_key)
        except Exception:
            pass
    return _local_followup(question, payload)
